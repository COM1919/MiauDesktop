#pragma once
// =============================================================================
// SettingsServer.h
// 主程序侧的设置服务：通过命名管道与独立的 WinUI3 设置程序（MiauSettings.exe）通信
//
// 线程模型：
//   · 服务线程：负责 accept 连接 + 读取请求 + 写回响应（不接触任何 UI/ImGui 状态）
//   · 主线程：每帧调用 Tick()，处理挂起的请求（收集状态 / 应用命令），再把响应交回服务线程
// =============================================================================

namespace SettingsServer
{
    // 启动服务线程并开始监听管道
    void Start();
    // 停止服务线程（阻塞等待线程退出）
    void Stop();
    // 主线程每帧调用：处理来自设置程序的请求
    void Tick();
}
